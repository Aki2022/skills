"""Generate a data-only Tailwind config from already resolved token values."""
import hashlib
import json


def tailwind_artifact(tokens):
    colors = {path.replace('.', '-'): token['css'] for path, token in sorted(tokens.items())
              if token['type'] == 'color'}
    if not colors:
        raise ValueError('no resolved colors for Tailwind')
    content = '// Generated by design-author. Do not edit.\nmodule.exports = ' + json.dumps(
        {'content':['./**/*.{html,js,jsx,ts,tsx,mdx}'], 'theme': {'colors':colors}, 'plugins':[]},
        ensure_ascii=False, sort_keys=True, indent=2) + ';\n'
    return {'content':content, 'sha256':hashlib.sha256(content.encode()).hexdigest()}


def _theme(value, tokens):
    if isinstance(value, dict):
        if '$token' in value:
            if set(value) - {'$token','mode'} or value['$token'] not in tokens:
                raise ValueError('unknown Tailwind token or field')
            token = tokens[value['$token']]
            if value.get('mode', 'value') not in ('value','css'):
                raise ValueError('unknown Tailwind token output mode')
            return (token['value'] if token['type'] in ('fontFamily','number','fontWeight')
                    and value.get('mode') != 'css' else token['css'])
        if '$format' in value:
            parts = value['$format']
            if set(value) != {'$format'} or not isinstance(parts,list) or not any(isinstance(p,dict) for p in parts):
                raise ValueError('invalid Tailwind format')
            import re
            if any(isinstance(p,str) and re.search(r'[0-9#;{}]',p) for p in parts):
                raise ValueError('literal numeric/color value in Tailwind format')
            return ''.join(p if isinstance(p,str) else str(_theme(p,tokens)) for p in parts)
        if any(str(key).startswith('$') for key in value):
            raise ValueError('unknown Tailwind directive')
        return {key:_theme(child,tokens) for key,child in value.items()}
    if isinstance(value,list):
        return [_theme(child,tokens) for child in value]
    raise ValueError('Tailwind theme values must reference resolved tokens')


def build_artifacts(tokens, templates=None):
    if templates is None:
        return ({'tailwind.config.cjs':tailwind_artifact(tokens)}
                if any(t['type']=='color' for t in tokens.values()) else {})
    import re
    from pathlib import PurePosixPath
    if not isinstance(templates,dict) or set(templates) != {'schema_version','configs'} or templates['schema_version'] != 1:
        raise ValueError('invalid Tailwind template schema')
    configs = templates['configs']
    if not isinstance(configs,list) or not configs:
        raise ValueError('zero Tailwind targets')
    artifacts = {}
    for config in configs:
        if not isinstance(config,dict) or set(config) != {'target','content','theme','plugins'}:
            raise ValueError('unknown Tailwind config fields')
        target = config['target']
        if not isinstance(target,str) or not target or '\\' in target:
            raise ValueError('invalid Tailwind target')
        path = PurePosixPath(target)
        if path.is_absolute() or '..' in path.parts or str(path) != target or not re.fullmatch(r'tailwind\.config\.(js|cjs)',path.name):
            raise ValueError('Tailwind target must be a repository-relative config path')
        if target in artifacts:
            raise ValueError('duplicate Tailwind target')
        content = config['content']
        if not isinstance(content,list) or not content or any(not isinstance(p,str) or not p.strip() for p in content):
            raise ValueError('zero Tailwind content targets')
        theme = _theme(config['theme'],tokens)
        plugins = config['plugins']
        if not isinstance(plugins,list):
            raise ValueError('plugins must be declarative module records')
        expressions = []
        for plugin in plugins:
            if not isinstance(plugin,dict) or set(plugin) - {'module','options'}:
                raise ValueError('invalid Tailwind plugin')
            module = plugin.get('module','')
            if not isinstance(module,str) or not re.fullmatch(r'(?:@[a-z0-9-]+/)?[a-z0-9-]+',module):
                raise ValueError('invalid Tailwind plugin module')
            expression = 'require(' + json.dumps(module) + ')'
            if 'options' in plugin:
                if not isinstance(plugin['options'],dict):
                    raise ValueError('Tailwind plugin options must be data')
                expression += '(' + json.dumps(plugin['options'],ensure_ascii=False,sort_keys=True) + ')'
            expressions.append(expression)
        body = json.dumps({'content':content,'theme':theme},ensure_ascii=False,sort_keys=True,indent=2)
        output = '// Generated by design-author. Do not edit.\nmodule.exports = ' + body[:-2] + ',\n  "plugins": [' + ', '.join(expressions) + ']\n};\n'
        artifacts[target] = {'content':output,'sha256':hashlib.sha256(output.encode()).hexdigest(),
                             'file':'tailwind-' + hashlib.sha256(target.encode()).hexdigest() + '.cjs'}
    return artifacts
